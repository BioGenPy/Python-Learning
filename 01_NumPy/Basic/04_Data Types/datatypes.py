print("For i, can define size as well.")
stArry = np.array([1, 2, 3, 4], dtype="i4")
print(stArry)
print(stArry.dtype)
print("For  u  can define size as well.")
stArry = np.array([1, 2, 3, 4], dtype="u4")
print(stArry)
print(stArry.dtype)

print("For  f  we can define size as well.")
stArry = np.array([1, 2, 3, 4], dtype="f4")
print(stArry)
print(stArry.dtype)
print("For  S we can define size as well.")
stArry = np.array([1, 2, 3, 4], dtype="S4")
print(stArry)
print(stArry.dtype)

print("For  U we can define size as well.")
stArry = np.array([1, 2, 3, 4], dtype="U4")
print(stArry)
